"""
S4 report (scope v2 §9.3, §9.6, F7): retrieval on test for every S4 configuration, plus the
judge-free generation metrics (§8.4), latency means/medians and cost (§8.5) for the configurations
that have answers. Generated — never hand-edit the numbers.

- CIs: question bootstrap (10,000 resamples, 95%, `evals.stats`). Paired differences vs the
  baseline on the questions both answered; p-values Holm-adjusted per metric across the
  configurations compared (§9.6).
- `answered` = answerable questions not refused (the complement of the refusal rate on answerable
  questions, whatever retrieval found).
- A configuration with fewer answers than questions, or with errors, marks the report PARTIAL: its
  numbers are not quotable (F7).
- Judge-based metrics (answer correctness, faithfulness) are not in this report yet (§8.6 gate).

    venv/bin/python -m evals.generation.report --split test
"""
from __future__ import annotations

import argparse
import json
import statistics
import sys
from pathlib import Path

from evals import stats as ST
from evals.generation import run as GR
from evals.report import ci_cell, diff_cell, md_table, p_cell
from evals.run import file_sha256

REPO = Path(__file__).resolve().parents[2]
CONFIG = REPO / "evals" / "configs" / "s4_generation.yaml"
DOC = REPO / "docs" / "25_s4_generation.md"
BASELINE = "C1-dense"
RETRIEVAL_METRICS = ("recall@budget", "entity_recall")
GEN_METRICS = (   # (key, label)
    ("answer_entity_recall", "Answer entity recall"),
    ("answered", "Answered (answerable Qs)"),
    ("numeric_em", "Numeric exact match (calculation)"),
    ("refusal_correct", "Refusal correctness (unanswerable)"),
    ("false_refusal", "False refusal (evidence in context)"),
    ("stale", "Stale answer (amendment)"),
    ("citation_precision", "Citation precision"),
    ("citation_recall", "Citation recall"),
    ("format_ok", "Format compliance"),
)
LOWER_IS_BETTER = {"false_refusal", "stale"}
LATENCY = (("ttft", "TTFT"), ("ttfs", "TTFS"), ("inter_token", "Inter-token"), ("e2e", "Generation e2e"),
           ("retrieval", "Retrieval"), ("e2e_total", "End-to-end"))


def metric_value(a: dict, key: str) -> float | None:
    if key == "answered":
        return None if a["type"] == "unanswerable" else float(not a["metrics"]["refused"])
    v = a["metrics"].get(key)
    return None if v is None else float(v)


def load(cfg, split: str, retrieval_root: Path, out_root: Path):
    retr, gen = {}, {}
    for r in cfg.runs:
        d = GR.retrieval_dir(r, split, retrieval_root)
        if (d / "summary.json").exists():
            s = json.loads((d / "summary.json").read_text())
            if s.get("limit") is None:
                retr[r.name] = {row["qid"]: row for row in GR.read_jsonl(d / "questions.jsonl")}
        answers = GR.read_jsonl(GR.out_dir(cfg, r, split, out_root) / "answers.jsonl")
        if answers:
            gen[r.name] = answers
    return retr, gen


def _cmp_rows(names: list[str], base: str, get, qids: list[str], lower_better: bool = False) -> list[list[str]]:
    others = [n for n in names if n != base]
    diffs = [ST.paired_diff_ci([get(base, q) for q in qids], [get(n, q) for q in qids]) for n in others]
    adj = ST.holm([d["p"] if d["p"] is not None else 1.0 for d in diffs]) if diffs else []
    rows = []
    for n, d, p in zip(others, diffs, adj):
        if d["diff"] is None:
            v = "–"
        elif d["better"] is None or p >= ST.ALPHA:
            v = f"no detectable difference (n = {d['n']})"
        else:
            good = (d["better"] == "b") != lower_better
            v = f"{n} {'better' if good else 'worse'}"
        rows.append([n, diff_cell(d), p_cell(d["p"]), p_cell(p), v])
    return rows


def render(cfg, split: str, retr: dict, gen: dict, questions_n: int, provenance: dict) -> str:
    out = [f"# S4 — generation on {split} (generated by `evals.generation.report`)", ""]
    partial = [n for n, a in gen.items() if len([x for x in a if "error" not in x]) < questions_n
               or any("error" in x for x in a)]
    if partial:
        out += [f"> **PARTIAL — not quotable (F7).** Incomplete or with errors: {', '.join(partial)}.", ""]
    out += ["Judge-based metrics (answer correctness, faithfulness) are pending judge calibration (§8.6). "
            "Everything below is deterministic.", ""]

    # retrieval
    if retr:
        names = list(retr)
        qids = sorted(set.intersection(*(set(r) for r in retr.values())))
        out += ["## Retrieval on the test split", ""]
        rows = []
        for n in names:
            rows.append([n] + [ci_cell(ST.bootstrap_ci([retr[n][q]["metrics"].get(m) for q in qids]))
                               for m in RETRIEVAL_METRICS])
        out += [md_table(["Configuration", "recall@budget", "entity recall"], rows), "",
                f"n = {sum(retr[names[0]][q]['metrics'].get('recall@budget') is not None for q in qids)} "
                "answerable questions. 95% bootstrap CIs.", ""]
        if BASELINE in retr:
            out += [f"Paired difference vs {BASELINE} (recall@budget, Holm-adjusted):", ""]
            out += [md_table(["Configuration", "Δ [95% CI]", "p", "p (Holm)", "Verdict"],
                             _cmp_rows(names, BASELINE, lambda n, q: retr[n][q]["metrics"].get("recall@budget"),
                                       qids)), ""]

    if not gen:
        return "\n".join(out + ["No generation results yet."]) + "\n"

    # generation
    names = list(gen)
    by = {n: {a["qid"]: a for a in gen[n] if "error" not in a} for n in names}
    qids = sorted(set.intersection(*(set(b) for b in by.values())))
    out += ["## Generation quality (judge-free)", "",
            f"Paired question set: **{len(qids)}** questions answered by every configuration below.", ""]
    rows = []
    for key, label in GEN_METRICS:
        rows.append([label] + [ci_cell(ST.bootstrap_ci([metric_value(by[n][q], key) for q in qids]))
                               + f" (n {sum(metric_value(by[n][q], key) is not None for q in qids)})"
                               for n in names])
    out += [md_table(["Metric"] + names, rows), ""]
    if BASELINE in by and len(names) > 1:
        out += [f"### Paired differences vs {BASELINE} (Holm-adjusted per metric)", ""]
        rows = []
        for key, label in GEN_METRICS:
            for r in _cmp_rows(names, BASELINE, lambda n, q, k=key: metric_value(by[n][q], k), qids,
                               lower_better=key in LOWER_IS_BETTER):
                rows.append([label] + r)
        out += [md_table(["Metric", "Configuration", "Δ [95% CI]", "p", "p (Holm)", "Verdict"], rows), ""]

    # by type
    types = sorted({by[names[0]][q]["type"] for q in qids})
    out += ["### Answer entity recall / answered by question type", ""]
    rows = []
    for t in types:
        tq = [q for q in qids if by[names[0]][q]["type"] == t]
        key = "refusal_correct" if t == "unanswerable" else "answer_entity_recall"
        cells = []
        for n in names:
            vs = [metric_value(by[n][q], key) for q in tq]
            vs = [v for v in vs if v is not None]
            cells.append(f"{statistics.mean(vs):.3f}" if vs else "–")
        rows.append([f"{t} ({len(tq)})" + (" — refusal correctness" if t == "unanswerable" else "")] + cells)
    out += [md_table(["Type (n)"] + names, rows), ""]

    # latency + cost
    out += ["## Latency (seconds, client-side, native streaming)", "",
            "Means and medians only; percentiles come from the S5 load test (§8.5).", ""]
    rows = []
    for k, label in LATENCY:
        cells = []
        for n in names:
            xs = [by[n][q]["timings_s"].get(k) for q in qids]
            xs = [x for x in xs if x is not None]
            cells.append(f"{statistics.mean(xs):.3f} / {statistics.median(xs):.3f}" if xs else "–")
        rows.append([label + " (mean / median)"] + cells)
    tps = []
    for n in names:
        xs = [by[n][q]["timings_s"].get("tokens_per_s") for q in qids]
        xs = [x for x in xs if x is not None]
        tps.append(f"{statistics.median(xs):.0f}" if xs else "–")
    rows.append(["Output tokens/s (median)"] + tps)
    out += [md_table(["Metric"] + names, rows), ""]

    from evals.llm.ledger import PRICES
    out += ["## Tokens and cost (list prices, recorded even on the free tier — D7)", ""]
    rows = []
    for n in names:
        a = [by[n][q] for q in qids]
        pin, pout = PRICES[a[0]["model"]]
        ip = sum(x["prompt_tokens"] for x in a) * pin / 1e6
        op = sum(x["completion_tokens"] for x in a) * pout / 1e6
        rows.append([n, f"{statistics.mean(x['prompt_tokens'] for x in a):.0f}",
                     f"{statistics.mean(x['completion_tokens'] for x in a):.1f}",
                     f"${(ip + op) / len(a):.5f}", f"${1000 * (ip + op) / len(a):.2f}",
                     f"{100 * ip / (ip + op):.0f}% / {100 * op / (ip + op):.0f}%"])
    out += [md_table(["Configuration", "Input tokens (mean)", "Output tokens (mean)", "$ / query",
                      "$ / 1k queries", "Input / output cost"], rows), ""]
    errs = {n: sum("error" in x for x in gen[n]) for n in names}
    out += [f"Errors: {', '.join(f'{n} {e}' for n, e in errs.items())}.", ""]

    out += ["## Provenance", ""] + [f"- {k}: `{v}`" for k, v in provenance.items()] + [""]
    out += ["## Notes", "",
            "- **Answer entity recall** is a judge-free correctness proxy: share of the question's key values "
            "(numbers normalized) that appear in the answer; a refusal scores 0. It doesn't penalize extra wrong "
            "claims; answer correctness by the calibrated judge replaces it as the S4 decision metric.",
            "- Context = the retrieval run's in-budget chunks (production's 1,200-word rule). Prompt `cite-v1`: "
            "chunks labelled S1…Sn, mapped back to chunk ids for citation metrics.",
            "- False refusal is counted only when all evidence was in the context (recall@budget = 1).", ""]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--split", choices=["dev", "test"], default="test")
    ap.add_argument("--config", type=Path, default=CONFIG)
    ap.add_argument("--out", type=Path)
    a = ap.parse_args(argv)
    from evals.golden.qa.validate import QUESTIONS, read_questions
    cfg = GR.load_config(a.config)
    n = sum(1 for q in read_questions(QUESTIONS) if not q.get("retired") and q["split"] == a.split)
    retr, gen = load(cfg, a.split, GR.RETRIEVAL_ROOT, GR.OUT_ROOT)
    prov = {"generator": cfg.model, "temperature": cfg.temperature, "max_tokens": cfg.max_tokens,
            "prompt_version": next((x["prompt_version"] for g in gen.values() for x in g if "prompt_version" in x), "–"),
            "questions_sha256": file_sha256(QUESTIONS)[:16], "split": a.split, "questions in split": n}
    out = a.out or (DOC if a.split == "test" else REPO / "docs" / f"s4_{a.split}_generation.md")
    out.write_text(render(cfg, a.split, retr, gen, n, prov))
    print(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
